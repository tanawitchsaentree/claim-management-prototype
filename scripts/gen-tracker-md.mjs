#!/usr/bin/env node
// Regenerates /TRACKER.md from tracker-data/.
//
// Reads the local dump rather than curling Supabase directly, which is the whole
// point: the dump already withholds the manager's rows (see dump-tracker.mjs and
// src/app/core/services/tracker-visibility.ts), so TRACKER.md inherits that for
// free. The earlier throwaway version of this script curled the joined ticket
// table itself, which meant the committed TRACKER.md listed all 6 of her tickets
// by name while the app was hiding them.
//
// Usage: node scripts/dump-tracker.mjs && node scripts/gen-tracker-md.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const read = (name) => JSON.parse(readFileSync(`tracker-data/${name}.json`, 'utf8'));

const pis = read('pi');
const epics = read('epic');
const tickets = read('ticket');
const states = read('ticket_state');
const summary = read('_dump-summary');

const BASE = 'https://tanawitchsaentree.github.io/claim-management-prototype';

// Every path declared in src/app/app.routes.ts + src/app/features/fnol/fnol.routes.ts
const VALID = new Set([
  '/dashboard', '/administration', '/administration/mass-events', '/claims', '/loss-events',
  '/approvals', '/fnol', '/tracker', '/loss-events/:id/overview',
  '/claims/:id', '/claims/:id/overview', '/claims/:id/loss-information/edit',
  '/claims/:id/sections', '/claims/:id/policy', '/claims/:id/parties', '/claims/:id/financial',
  '/claims/:id/notes', '/claims/:id/limits', '/claims/:id/recoveries', '/claims/:id/providers',
  '/claims/:id/risk', '/claims/:id/litigation',
  '/fnol/search', '/fnol/skeleton-create', '/fnol/skeleton-parties', '/fnol/skeleton-location',
  '/fnol/skeleton-summary', '/fnol/loss-information', '/fnol/loss-details',
  '/fnol/entities-damages', '/fnol/parties', '/fnol/reserves', '/fnol/summary',
]);
const norm = (r) => r.replace(/\/claims\/CLM-[0-9-]+\//, '/claims/:id/');

// Same substitution as substituteClaimId()/DEMO_CLAIM_ID in
// src/app/core/services/prototype-scenario.service.ts — that file is the source of
// truth for what a tracker route resolves to; this is a node script and can't
// import it, so keep the two in step by hand. Anchored on a path segment so a
// route like "/claims/:idle" would not be mangled.
const DEMO_CLAIM_ID = 'CLM-2024-001';
const substituteClaimId = (r) => r.replace(/\/:id(?=\/|$)/g, `/${DEMO_CLAIM_ID}`);

const piName = (id) => pis.find((p) => p.id === id)?.name ?? '(no PI)';
const epicOf = (id) => epics.find((e) => e.id === id) ?? null;
const stateOf = new Map(states.map((s) => [s.ticket_id, s]));

const S = { done: '✅', in_progress: '🔄', not_started: '⬜', blocked: '⛔' };
const s = (v) => S[v] ?? v ?? '–';

const proto = (t) => {
  const r = stateOf.get(t.id)?.prototype_route;
  if (!r) return '–';
  if (!VALID.has(norm(r))) return '⚠️ `' + r + '` dead';
  return `[${r}](${BASE}${substituteClaimId(r)})`;
};
const blk = (t) => {
  const b = stateOf.get(t.id)?.blocked_by;
  return !b || b === 'none' ? '' : ' ⛔' + b;
};
const row = (t) => {
  const st = stateOf.get(t.id) ?? {};
  const cells = [
    `[${t.jira_key}](${t.jira_url})`,
    t.title.replace(/\|/g, '/').trim(),
    t.jira_status || '–',
    (t.assignee || '–').replace(/\s*\(.*\)/, ''),
    s(st.build_status),
    s(st.handoff_status) + blk(t),
    proto(t),
  ];
  return `| ${cells.join(' | ')} |`;
};

const HEAD = '| Ticket | Title | Jira | Assignee | B | H | Prototype |\n|---|---|---|---|---|---|---|';
const active = tickets.filter((t) => !t.archived);
const withheld = summary.find((r) => r.table === 'ticket')?.withheld_owner_rows ?? 0;
const lastSync = read('sync_log')[0];

const out = [
  '# Tracker — every ticket',
  '',
  `**${tickets.length} tickets** (${active.length} active, ${tickets.length - active.length} archived) across ${epics.length} epics and ${pis.length} PIs. `
    + `Generated by \`node scripts/gen-tracker-md.mjs\` from the \`tracker-data/\` dump, taken after the Jira sync on `
    + `${lastSync.started_at.slice(0, 10)} which refreshed ${lastSync.ticket_count} tickets.`,
  '',
  'B = build · H = handoff (design_status dropped from the app 2026-09-02 — it duplicated build). ✅ done · 🔄 in progress · ⬜ not started · ⛔ blocker flag. The ticket key links to Jira; the Prototype column links to the built screen on gh-pages (`:id` resolved to `CLM-2024-001`).',
  '',
  '## Read this before trusting the columns',
  '',
  "- `jira_status` is live only for the ~51 tickets inside the edge function's fixed JQL scope. Everything else shows `–`, which means *no data*, not *no status*. The JQL is a server-side Supabase secret and cannot be overridden per request.",
  '- `pi_id` is tagged by hand. The sync never reads `fixVersion`, so PI 2026.4 holds only a handful of rows here while Jira itself carries more under `fixVersion = PI 2026.4 CM`.',
  "- The 5 rows that pointed at non-existent routes were repaired in the tracker on 2026-09-02 (`risk-analysis` → `risk`, `financial-overview` → `financial`, `provider-management` → `providers`). They had looked like they worked because the app's `**` wildcard silently redirects an unknown path to `/dashboard`. Any row still marked ⚠️ below is a fresh one.",
];

if (withheld) {
  out.push(
    `- **${withheld} tickets are not listed.** They are the manager's own, hidden from everyone else in the app `
      + '(`src/app/core/services/tracker-visibility.ts`) and therefore withheld from the dump this file is built from. '
      + 'The totals above exclude them, so this file will not reconcile with a raw row count in Supabase.',
  );
}
out.push('');

const groups = new Map();
for (const t of tickets) {
  const epic = epicOf(t.epic_id);
  const k = piName(t.pi_id) + '||' + (epic ? `${epic.jira_key} — ${epic.title.trim()}` : '(no epic)');
  if (!groups.has(k)) groups.set(k, []);
  groups.get(k).push(t);
}

const order = [...groups.keys()].sort((a, b) => {
  const pa = a.split('||')[0];
  const pb = b.split('||')[0];
  return pa !== pb ? pb.localeCompare(pa) : a.localeCompare(b);
});
const num = (k) => parseInt(k.replace(/\D/g, ''), 10);

for (const k of order) {
  const [pi, epic] = k.split('||');
  const rows = groups.get(k).sort((a, b) => num(a.jira_key) - num(b.jira_key));
  const a = rows.filter((r) => !r.archived);
  const ar = rows.filter((r) => r.archived);
  out.push(`## ${pi} · ${epic}`, '');
  if (a.length) out.push(HEAD, ...a.map(row), '');
  else out.push('_No active tickets._', '');
  if (ar.length) {
    out.push(`<details><summary>archived — ${ar.length} ticket${ar.length > 1 ? 's' : ''}</summary>`, '', HEAD, ...ar.map(row), '', '</details>', '');
  }
}

writeFileSync('TRACKER.md', out.join('\n') + '\n');
console.log(`wrote TRACKER.md — ${tickets.length} tickets${withheld ? `, ${withheld} withheld` : ''}`);
