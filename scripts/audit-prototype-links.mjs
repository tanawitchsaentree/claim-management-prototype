#!/usr/bin/env node
// audit:prototype-links — every route a reviewer can be sent to must actually exist,
// and every ticket file must be able to explain itself when they get there.
//
// Why this exists: a tracker row's prototype_route is hand-typed, and a ticket file's
// howToTest.route is hand-typed. Neither is checked by the compiler. On 2026-09-02 that
// produced links landing on /claims/:id/sections LITERALLY — Angular matches the
// parameterised route with the id ":id", so the page rendered against a claim that does
// not exist and every field read "Not provided". It looked exactly like data loss.
// substituteClaimId() in prototype-scenario.service.ts fixes the :id case at runtime;
// this audit catches the rest — a route that was renamed, deleted, or typo'd — before
// it ships, plus the case where a ticket file has nothing to say on arrival.
//
// Scope note: tracker rows live in Supabase, not in this repo, so this audit cannot see
// them. It checks the committed half (public/tickets/*.json + the substitution helper's
// own regex against every route pattern the app declares). TRACKER.md is regenerated by
// scripts/gen-tracker-md.mjs, which shares the same DEMO_CLAIM_ID/substituteClaimId
// logic — if that drifts from the TS, the parity check at the bottom fails.

import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const TICKET_DIR = join(ROOT, 'public', 'tickets');

// Route files and the prefix each is mounted under (loadChildren in app.routes.ts).
const ROUTE_FILES = [
  ['src/app/app.routes.ts', ''],
  ['src/app/features/fnol/fnol.routes.ts', 'fnol'],
  ['src/app/features/tracker/tracker.routes.ts', 'tracker'],
];

// Paths in app.routes.ts children are written out in full ('claims/:id/sections'),
// so a flat scrape per file plus the lazy-mount prefix reconstructs every pattern
// without having to evaluate the TS.
const patterns = new Set();
for (const [file, prefix] of ROUTE_FILES) {
  const src = readFileSync(join(ROOT, file), 'utf8');
  for (const m of src.matchAll(/path:\s*'([^']*)'/g)) {
    const p = [prefix, m[1]].filter(Boolean).join('/');
    if (p && p !== '**') patterns.add('/' + p);
  }
}

function routeExists(route) {
  const want = route.replace(/^\//, '').split('/');
  for (const pattern of patterns) {
    const have = pattern.replace(/^\//, '').split('/');
    if (have.length !== want.length) continue;
    if (have.every((seg, i) => seg.startsWith(':') || seg === want[i])) return true;
  }
  return false;
}

const violations = [];
const notes = [];
let ticketCount = 0;
let fallbackTourCount = 0;

for (const file of readdirSync(TICKET_DIR)) {
  if (!file.endsWith('.json') || file === 'index.json') continue;
  ticketCount++;
  const ticket = JSON.parse(readFileSync(join(TICKET_DIR, file), 'utf8'));
  const acs = ticket.acceptanceCriteria || [];

  for (const ac of acs) {
    const route = ac.howToTest?.route;
    if (!route) {
      violations.push(`${file} :: ${ac.id} — howToTest.route is missing; the tracker link has nowhere to go`);
      continue;
    }
    // AC routes are supposed to be concrete. A param here would be navigated
    // literally, which is the bug this whole audit is named after.
    if (/\/:[a-zA-Z]/.test(route)) {
      violations.push(`${file} :: ${ac.id} — route '${route}' still contains a route param; write the concrete claim id (e.g. ${ticket.targetClaim ?? 'CLM-2024-001'})`);
    }
    if (!routeExists(route)) {
      violations.push(`${file} :: ${ac.id} — route '${route}' matches no path in app.routes.ts / fnol.routes.ts / tracker.routes.ts`);
    }
  }

  // Mirrors resolveTourSteps() in src/app/core/services/arrival-context.builder.ts:
  // an authored walkthrough wins, otherwise one is generated from the non-todo ACs.
  // A ticket that resolves to neither arrives with no orientation at all.
  const authored = (ticket.walkthroughSteps || []).length;
  const generatable = acs.filter((ac) => ac.buildStatus !== 'todo').length;
  if (authored === 0 && generatable === 0) {
    violations.push(`${file} — no walkthroughSteps and no non-todo acceptance criteria: nothing to show a reviewer who follows a link here`);
  }
  if (authored === 0 && generatable > 0) fallbackTourCount++;
}

// gen-tracker-md.mjs duplicates DEMO_CLAIM_ID and substituteClaimId so it can build
// links without importing TS. Duplication is fine; silent divergence is not — the
// whole point of one substitution rule is that the app and the generated TRACKER.md
// send reviewers to the same place.
const tsSrc = readFileSync(join(ROOT, 'src/app/core/services/prototype-scenario.service.ts'), 'utf8');
const mdSrc = readFileSync(join(ROOT, 'scripts/gen-tracker-md.mjs'), 'utf8');
const grab = (src) => ({
  id: src.match(/DEMO_CLAIM_ID\s*=\s*'([^']+)'/)?.[1] ?? null,
  // The replacement expression differs legitimately (the TS takes claimId as a
  // parameter, the script closes over the constant) — only the PATTERN has to match.
  re: src.match(/\.replace\((\/[^,]+?\/g),/)?.[1] ?? null,
});
const ts = grab(tsSrc);
const md = grab(mdSrc);
if (!ts.id || !ts.re) violations.push('prototype-scenario.service.ts — could not read DEMO_CLAIM_ID / substituteClaimId; this audit can no longer verify link parity');
else if (ts.id !== md.id || ts.re !== md.re) {
  violations.push(`substituteClaimId has drifted: TS uses (${ts.id}, ${ts.re}) but scripts/gen-tracker-md.mjs uses (${md.id}, ${md.re}) — TRACKER.md links and in-app links will disagree`);
}

if (violations.length > 0) {
  console.error('\n✘ audit:prototype-links — violations found:\n');
  for (const v of violations) console.error('  •', v);
  console.error(`\n${violations.length} broken prototype link(s). A reviewer following one lands on the wrong screen or on no explanation.\n`);
  process.exit(1);
}

notes.push(`${ticketCount} ticket file(s), ${patterns.size} route pattern(s) declared`);
notes.push(`${fallbackTourCount} ticket(s) rely on the generated fallback tour`);
console.log(`✓ audit:prototype-links — ${notes.join('; ')}`);
